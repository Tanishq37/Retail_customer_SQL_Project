/* ------------------------------------------------------------
   Question 1:
   Which product categories generate the most revenue?
   ------------------------------------------------------------ */

SELECT
    Category,
    SUM(Purchase_Amount_USD) AS Revenue
FROM retail_customer_insights
GROUP BY Category
ORDER BY Revenue DESC;


/* ------------------------------------------------------------
   Question 2:
   Which season generates the highest revenue?
   ------------------------------------------------------------ */

SELECT
    Season,
    SUM(Purchase_Amount_USD) AS Revenue
FROM retail_customer_insights
GROUP BY Season
ORDER BY Revenue DESC;



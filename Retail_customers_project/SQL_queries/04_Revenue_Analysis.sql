/* ------------------------------------------------------------
   Question 9:
   What is the average revenue generated per category?
   ------------------------------------------------------------ */

SELECT
    Category,
    ROUND(AVG(Purchase_Amount_USD),2) AS Avg_Revenue
FROM retail_customer_insights
GROUP BY Category
ORDER BY Avg_Revenue DESC;


/* ------------------------------------------------------------
   Question 10:
   Which category performs best during each season?
   ------------------------------------------------------------ */

SELECT
    Season,
    Category,
    SUM(Purchase_Amount_USD) AS Revenue
FROM retail_customer_insights
GROUP BY Season, Category
ORDER BY Season, Revenue DESC;


